export function fill(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

/** Polish cardinal forms: 1 / 2–4 / 5+ (with the 12–14 exception). */
export function pluralForm(count: number): "one" | "few" | "many" {
  const abs = Math.abs(count);
  if (abs === 1) return "one";
  const mod10 = abs % 10;
  const mod100 = abs % 100;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return "few";
  return "many";
}

export function knownError(message: string): MessageKey | null {
  return KNOWN_ERRORS[message] ?? null;
}

/** Fixed English labels and notes the server stores or sends, keyed by their exact text. Patterns are matched separately. */
const SERVER_TEXT: Record<string, MessageKey> = Object.fromEntries(
  (Object.keys(en) as MessageKey[])
    .filter((key) => key.startsWith("server.") && !key.startsWith("server.pattern"))
    .map((key) => [en[key], key]),
);

export function serverTextKey(text: string): MessageKey | null {
  return SERVER_TEXT[text] ?? null;
}

