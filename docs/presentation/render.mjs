import { launch } from "./lib.mjs";
const b = await launch();
const p = await b.newPage();
await p.setViewport({ width: 1920, height: 1080, deviceScaleFactor: 1 });
await p.goto("file://" + new URL("./deck.html", import.meta.url).pathname, { waitUntil: "networkidle0" });
await p.evaluate(() => document.fonts.ready);
const n = await p.$$eval(".slide", (s) => s.length);
const els = await p.$$(".slide");
for (let i = 0; i < n; i++) await els[i].screenshot({ path: `/tmp/mradar-preview-${String(i + 1).padStart(2, "0")}.png` });
await p.pdf({ path: "mradar-submission.pdf", width: "1920px", height: "1080px", printBackground: true, preferCSSPageSize: true });
console.log(n, "slides");
await b.close();
